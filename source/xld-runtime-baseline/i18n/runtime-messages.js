  function createRuntimeTranslator(localeBridge) {
    if (!localeBridge) throw new Error('xld-runtime-locale-bridge-missing');
    return Object.freeze({
      t: (key, params) => translateRuntime(localeBridge.getState().locale, key, params),
      localizeBackendMessage: message => localizeBackendMessage(message, localeBridge.getState().locale),
      locale: () => localeBridge.getState().locale
    });
  }

